export const decemberTitle = 'Пояснение по Дням единых действий в декабре';
export const journalRule = 'Событие, проведённое для другого конкурсного задания, в «Бортовой журнал» не включают.';
export const journalGuidance = 'В «Бортовой журнал» принимают до четырёх ДЕД за весь Общий зачёт, по 4 балла за зачтённое мероприятие. Сверьте акцию с официальным перечнем, проведите её по условиям, сохраните итоговый пост и число участников.';
export const decemberExample = 'Отдельную классную встречу можно подать в № 2 «Бортовой журнал», а отдельно проведённую выставку «Герои моей малой Родины» — в № 12 «История в предметах». Если встреча входит в открытие выставки, это одно событие.';
export const rulesLink = 'https://t.me/konkurs_pervichek/476';

export function matchesLeague(match, league) {
  return !league || match.targets.some(target => target.startsWith(league + '-') ||
    (league === 'pl' && target.startsWith('lv-') && target !== 'lv-15/solo'));
}

export function taskRecommendations(league, key, variant) {
  if (variant === 'journal') {
    return [{
      title: 'Декабрьские ДЕД',
      description: decemberActions.map(action => '«' + action.title + '» (' + action.period + ')').join(', ') + '. ' + journalGuidance,
      source: 'прил. № 1 и № 2, п. 2.1–2.3, с. 12–13 и 47–48'
    }];
  }
  return decemberActions.flatMap(action => action.matches
    .filter(match => match.targets.includes(key + '/' + variant) && matchesLeague(match, league))
    .map(match => ({
      title: match.format + ' · ' + action.period,
      description: match.conditions,
      source: match.source
    })));
}

function element(tag, text, className) {
  const node = document.createElement(tag);
  if (text) node.textContent = text;
  if (className) node.className = className;
  return node;
}

function orderSource() {
  const link = element('a', 'Порядок в канале конкурса');
  link.href = rulesLink;
  link.target = '_blank';
  link.rel = 'noopener noreferrer';
  return link;
}

export function createDecemberNotice() {
  const notice = element('details', '', 'december-notice');
  notice.append(
    element('summary', decemberTitle),
    element('p', 'Формат акции можно взять за основу. До анонса выберите задание своей лиги и выполните его условия по Порядку.'),
    element('p', journalGuidance + ' ' + journalRule),
    element('p', decemberExample),
    orderSource()
  );
  return notice;
}

export function renderActionMatches(action, league) {
  const list = element('dl', '', 'december-matches');
  for (const match of action.matches.filter(row => matchesLeague(row, league))) {
    const item = element('dd', match.conditions);
    item.append(element('small', 'Порядок · ' + match.source, 'december-cite'));
    list.append(element('dt', match.label), item);
  }
  return list;
}

export function appendTaskRecommendations(root, league, key, variant) {
  const rows = taskRecommendations(league, key, variant);
  if (!rows.length) return;
  const guidance = element('details', '', 'december-notice cl-fold cl-december');
  guidance.append(element('summary', 'Как использовать декабрьские акции'));
  const list = element('dl', '', 'december-matches');
  for (const row of rows) {
    const item = element('dd', row.description);
    item.append(element('small', 'Порядок · ' + row.source, 'december-cite'));
    list.append(element('dt', row.title), item);
  }
  guidance.append(list, element('p', journalRule), orderSource());
  root.append(guidance);
}
